// WAP which accept number from a user and display all its non-factors

#include<stdio.h>
#include<stdlib.h>

////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name   :   NonFact
//  Input           :   Integer
//  Output          :   Integers
//  Description     :   Displays all non factors of a number
//  Date            :   9/11/2026
//  Author          :   Anushka Anil Harpale
//
////////////////////////////////////////////////////////////////////////////////////////////////

void NonFact (int iNo)
{
    int iCnt = 0;

    if (iNo < 0)
    {
        iNo = -iNo;
    }

    for (iCnt = 1; iCnt < iNo; iCnt++)
    {
        if ((iNo % iCnt) != 0)
        {
            printf("%d\t", iCnt);
        }
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point of the application
//
////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter a number : ");
    scanf("%d", &iValue);

    NonFact(iValue);

    return EXIT_SUCCESS;
}

